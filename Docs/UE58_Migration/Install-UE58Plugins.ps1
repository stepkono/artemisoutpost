<#
.SYNOPSIS
  Swaps the project plugins (Meta XR, Meta XR Platform, Cesium) for their UE 5.8 versions and
  re-applies the ArtemisOutpost Meta XR fixes. Does not compile anything.

.DESCRIPTION
  For every zip you pass:
    1. extracts it to a temp folder and finds the plugin by its .uplugin file
    2. moves the old plugin folder out of the project into -BackupDir (never deletes it)
    3. copies the new plugin into <project>\Plugins
    4. removes the plugin's prebuilt Binaries and Intermediate, so your next build compiles it
       against UE 5.8 (works around the Meta 207.0 "built for 5.7.0" module load error)
    5. sets "EngineVersion" in the .uplugin to -EngineVersion
  Then it runs Apply-MetaXRPatches.ps1 on the new Meta XR plugin.
  The old Cesium texture-guard patch is NOT re-applied, it was only needed for a NullRHI
  dedicated server and the project now runs a listen server.

  Close the Unreal Editor and your IDE before running it.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\Install-UE58Plugins.ps1 `
     -MetaXRZip   "$env:USERPROFILE\Downloads\UnrealMetaXRPlugin.207.0.zip" `
     -PlatformZip "$env:USERPROFILE\Downloads\Unreal5PlatformSDKPlugin.207.0.zip" `
     -CesiumZip   "$env:USERPROFILE\Downloads\CesiumForUnreal-58-v2.31.0.zip" `
     -CleanProject
#>
[CmdletBinding()]
param(
    [string]$MetaXRZip,
    [string]$PlatformZip,
    [string]$CesiumZip,
    [string]$ProjectRoot = '',
    [string]$BackupDir = '',
    [string]$EngineVersion = '5.8.0',
    [switch]$IgnoreRunningEditor,  # only for testing on a copy
    [switch]$CleanProject   # also delete the project's Binaries, Intermediate, .vs and .sln (regenerated by the build)
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $ProjectRoot) { $ProjectRoot = (Resolve-Path (Join-Path $here '..\..')).Path }
if (-not (Test-Path (Join-Path $ProjectRoot '*.uproject'))) { throw "No .uproject in $ProjectRoot" }
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
if (-not $BackupDir) { $BackupDir = Join-Path (Split-Path -Parent $ProjectRoot) ("ArtemisOutpost_PluginBackup_$stamp") }
$PluginsDir = Join-Path $ProjectRoot 'Plugins'

if (-not $IgnoreRunningEditor -and (Get-Process -Name 'UnrealEditor*' -ErrorAction SilentlyContinue)) {
    throw 'Unreal Editor is running. Close it first.'
}

# Deletes a folder tree, also when paths exceed 260 characters (deep Intermediate folders).
function Remove-Tree([string]$path) {
    if (-not (Test-Path $path)) { return }
    $full = (Resolve-Path $path).ProviderPath
    cmd /c "rd /s /q `"\\?\$full`"" | Out-Null
    if (Test-Path $full) { throw "Could not delete $full" }
}

# Finds the project plugin folder that holds a given .uplugin file name.
function Find-PluginDir([string]$root, [string]$upluginName) {
    $f = Get-ChildItem -Path $root -Filter $upluginName -Recurse -Depth 3 -ErrorAction SilentlyContinue |
         Where-Object { $_.FullName -notmatch '\\(Binaries|Intermediate)\\' } | Select-Object -First 1
    if ($f) { return $f.Directory.FullName }
    return $null
}

function Install-PluginZip([string]$zip, [string]$upluginName, [string]$label) {
    if (-not $zip) { Write-Host "[$label] skipped (no zip given)"; return $null }
    if (-not (Test-Path $zip)) { throw "[$label] zip not found: $zip" }

    # Extract next to the project: Move-Item cannot move folders across drives.
    $tmp = Join-Path (Split-Path -Parent $ProjectRoot) "_ue58_$label`_$stamp"
    Write-Host "[$label] extracting $zip"
    [IO.Compression.ZipFile]::ExtractToDirectory($zip, $tmp)
    $newDir = Find-PluginDir $tmp $upluginName
    if (-not $newDir) { throw "[$label] $upluginName not found inside $zip" }

    $oldDir = Find-PluginDir $PluginsDir $upluginName
    if ($oldDir) {
        New-Item -ItemType Directory -Force $BackupDir | Out-Null
        $dest = Join-Path $BackupDir (Split-Path -Leaf $oldDir)
        Write-Host "[$label] backing up $oldDir -> $dest"
        Move-Item $oldDir $dest
    }

    $target = Join-Path $PluginsDir (Split-Path -Leaf $newDir)
    if (Test-Path $target) { throw "[$label] $target still exists, aborting" }
    Write-Host "[$label] installing -> $target"
    foreach ($sub in 'Binaries', 'Intermediate') {
        $p = Join-Path $newDir $sub
        if (Test-Path $p) { Remove-Tree $p; Write-Host "[$label] removed prebuilt $sub" }
    }
    Move-Item $newDir $target
    Remove-Tree $tmp

    $up = Join-Path $target $upluginName
    $json = [IO.File]::ReadAllText($up)
    $ver = [regex]::Match($json, '"VersionName"\s*:\s*"([^"]*)"').Groups[1].Value
    $old = [regex]::Match($json, '"EngineVersion"\s*:\s*"([^"]*)"').Groups[1].Value
    if ($old -and $old -ne $EngineVersion) {
        $json = [regex]::Replace($json, '("EngineVersion"\s*:\s*")[^"]*(")', "`${1}$EngineVersion`${2}")
        [IO.File]::WriteAllText($up, $json, (New-Object System.Text.UTF8Encoding($false)))
        Write-Host "[$label] EngineVersion $old -> $EngineVersion"
    }
    Write-Host "[$label] installed version $ver"
    return $target
}

$meta = Install-PluginZip $MetaXRZip   'OculusXR.uplugin'         'MetaXR'
$null = Install-PluginZip $PlatformZip 'OculusPlatform.uplugin'   'MetaXRPlatform'
$null = Install-PluginZip $CesiumZip   'CesiumForUnreal.uplugin'  'Cesium'

if ($meta) {
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $here 'Apply-MetaXRPatches.ps1') -PluginRoot $meta
    if ($LASTEXITCODE -ne 0) { Write-Warning 'Meta XR patching reported REVIEW items, see output above.' }
}

if ($CleanProject) {
    foreach ($p in 'Binaries', 'Intermediate', '.vs') {
        $full = Join-Path $ProjectRoot $p
        if (Test-Path $full) { Remove-Tree $full; Write-Host "[Project] removed $p" }
    }
    Get-ChildItem $ProjectRoot -Filter *.sln | Remove-Item -Force
}

Write-Host ''
Write-Host "Done. Old plugins are in: $BackupDir"
Write-Host 'Next: right-click ArtemisOutpost.uproject > Switch Unreal Engine version > 5.8, then build Development Editor.'
